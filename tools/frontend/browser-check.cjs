// Run against the test-only browser_fixture example. Never use production credentials.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({executablePath: process.env.CHROMIUM_PATH, headless: true, args: ['--no-sandbox']});
  const page = await browser.newPage({viewport: {width: 1440, height: 1000}, colorScheme: 'dark'});
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', msg => {if (msg.type() === 'error' && !msg.text().includes('401')) errors.push(msg.text());});
  await page.goto('http://127.0.0.1:19581');
  await page.getByRole('heading', {name:'Sign in', exact:true}).waitFor();
  const asset = await page.request.get('http://127.0.0.1:19581/assets/bootstrap.js', {headers: {'Accept-Encoding': 'gzip'}});
  assert.equal(asset.headers()['content-encoding'], 'gzip');
  assert.equal(asset.headers()['cache-control'], 'no-store');
  assert.equal(await page.getByRole('link', {name:/sign up|reset password/i}).count(), 0);
  const theme = page.getByLabel('Color theme');
  await theme.selectOption('dark');
  await page.screenshot({path:'/tmp/lqosync-signin-dark.png',fullPage:true});
  await theme.selectOption('light');
  await page.reload();
  await page.getByRole('heading', {name:'Sign in',exact:true}).waitFor();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'light');
  await page.screenshot({path:'/tmp/lqosync-signin-light.png',fullPage:true});
  await page.getByLabel('Color theme').selectOption('system');
  await page.emulateMedia({colorScheme:'dark'});
  assert.equal(await page.locator('html').evaluate(el=>getComputedStyle(el).getPropertyValue('--bg').trim()), '#0b0e13');
  await page.emulateMedia({colorScheme:'light'});
  assert.equal(await page.locator('html').evaluate(el=>getComputedStyle(el).getPropertyValue('--bg').trim()), '#edf2f8');
  await page.setViewportSize({width:320,height:900});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'/tmp/lqosync-signin-mobile.png',fullPage:true});
  await page.getByLabel('Username',{exact:true}).fill('browser-test');
  await page.getByLabel('Password',{exact:true}).fill(process.env.BROWSER_TEST_PASSWORD);
  await page.getByRole('button',{name:'Show password',exact:true}).click();
  assert.equal(await page.locator('#password').getAttribute('type'),'text');
  await page.getByRole('button',{name:'Hide password',exact:true}).click();
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByRole('heading',{name:'Dashboard',exact:true}).waitFor();
  await page.getByText('Current data',{exact:false}).waitFor();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'/tmp/lqosync-dashboard-mobile.png',fullPage:true});
  const cookies = await page.context().cookies();
  assert.ok(cookies.find(c=>c.name==='lqosync_session' && c.httpOnly && c.sameSite==='Strict'));
  assert.ok(!(await page.evaluate(()=>document.cookie)).includes('lqosync_session'));
  await page.setViewportSize({width:1440,height:1000});
  await page.getByLabel('Color theme').selectOption('dark');
  await page.screenshot({path:'/tmp/lqosync-dashboard-dark.png',fullPage:true});
  await page.getByLabel('Color theme').selectOption('light');
  await page.screenshot({path:'/tmp/lqosync-dashboard-light.png',fullPage:true});
  await page.reload();
  await page.getByRole('heading',{name:'Dashboard',exact:true}).waitFor();
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await page.getByRole('heading',{name:'Sign in',exact:true}).waitFor();
  const status = await page.evaluate(async()=>(await fetch('/api/v1/overview')).status);
  assert.equal(status,401);
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('PASS: sign-in, themes, system changes, 320px layout, dashboard, session persistence, logout, no browser errors.');
})().catch(e=>{console.error(e);process.exit(1)});
